// Helper to initialize or retrieve menu data from localStorage with auto-upgrade
function getMenuDatabase() {
  const storedVersion = localStorage.getItem("shreeji_canteen_version");
  const stored = localStorage.getItem("shreeji_canteen_menu");

  if (stored && storedVersion === MENU_DATA_VERSION) {
    try {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    } catch (e) {
      console.error("Failed to parse stored menu, resetting to defaults", e);
    }
  }

  // Upgrade or set new menu data with local images
  localStorage.setItem("shreeji_canteen_version", MENU_DATA_VERSION);
  localStorage.setItem("shreeji_canteen_menu", JSON.stringify(DEFAULT_MENU_ITEMS));
  return DEFAULT_MENU_ITEMS;
}

function saveMenuDatabase(items) {
  localStorage.setItem("shreeji_canteen_version", MENU_DATA_VERSION);
  localStorage.setItem("shreeji_canteen_menu", JSON.stringify(items));
}
